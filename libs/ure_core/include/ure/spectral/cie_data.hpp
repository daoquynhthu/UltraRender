inline float interpolate_cie(float lambda, const std::array<float, kCieCount>& table) {
    if (lambda <= kCieStart) return table.front();
    if (lambda >= kCieEnd) return table.back();
    
    float t = (lambda - kCieStart) / kCieStep;
    int idx = static_cast<int>(t);
    float frac = t - idx;
    
    return table[idx] * (1.0f - frac) + table[idx + 1] * frac;
}

